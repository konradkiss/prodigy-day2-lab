/*
 * What the guardrails protect, shared by scripts/check.mjs and the hooks in scripts/hooks/:
 *   - the protected paths: the checks' configuration, scripts/ and the agents' settings;
 *   - the suppressions: ways to switch a check off instead of fixing what it found.
 */
import { existsSync, readFileSync } from 'node:fs';
import { basename, dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

/* Directories (trailing slash) and files, relative to the root. scripts/hooks/locked-paths.json adds more (npm run lock-rules). */
const PROTECTED = [
  'scripts/', '.claude/', '.codex/', '.config/dotnet-tools.json',
  '.secretlintrc.json', '.secretlintignore', 'CodeMetricsConfig.txt', 'package.json', 'package-lock.json',
];
/* File names protected wherever they are: MSBuild and analyzer configuration applies to every directory below it. */
const PROTECTED_NAMES = ['Directory.Build.props', 'Directory.Build.targets', 'Directory.Packages.props', '.editorconfig', '.globalconfig'];
const LOCKED = join(ROOT, 'scripts', 'hooks', 'locked-paths.json');

export function protectedPaths() {
  const locked = existsSync(LOCKED) ? JSON.parse(readFileSync(LOCKED, 'utf8')) : [];
  return [...PROTECTED, ...locked];
}

export function protectedNames() {
  return PROTECTED_NAMES;
}

/* A path relative to the root with forward slashes, or null when it lies outside the repository. */
export function repoPath(file, cwd = process.cwd()) {
  const rel = relative(ROOT, isAbsolute(file) ? file : resolve(cwd, file)).replaceAll('\\', '/');
  return rel.startsWith('../') || rel === '..' || isAbsolute(rel) ? null : rel;
}

/* Why a repository path is protected, or null. Case-insensitive: macOS and Windows file systems are. */
export function protectedReason(rel) {
  if (rel === null) return null;
  const path = rel.toLowerCase();
  const name = basename(path);
  if (PROTECTED_NAMES.some((n) => n.toLowerCase() === name) || name.endsWith('.globalconfig')) return `${rel} configures the checks`;
  const hit = protectedPaths().find((p) => {
    const q = p.toLowerCase();
    return q.endsWith('/') ? path.startsWith(q) || `${path}/` === q : path === q;
  });
  return hit ? `${rel} is protected (${hit})` : null;
}

/* C# source with comments, string and char literals blanked (line breaks kept), so a pattern only matches code. */
export function codeOnly(source) {
  let out = '';
  let i = 0;
  const skip = (to, stub) => { out += stub + source.slice(i, to).replace(/[^\n]/g, ''); i = to; };
  const after = (end, from) => { const j = source.indexOf(end, from); return j < 0 ? source.length : j + end.length; };
  while (i < source.length) {
    const rest = source.slice(i, i + 3);
    if (rest.startsWith('//')) { const j = source.indexOf('\n', i); skip(j < 0 ? source.length : j, ''); continue; }
    if (rest.startsWith('/*')) { skip(after('*/', i + 2), ' '); continue; }
    if (rest === '"""') { skip(after('"""', i + 3), '""'); continue; }
    if (rest.startsWith('@"') || rest.startsWith('$@') || rest.startsWith('@$')) {
      let j = source.indexOf('"', i) + 1;
      while (j < source.length && !(source[j] === '"' && source[j + 1] !== '"')) j += source[j] === '"' ? 2 : 1;
      skip(Math.min(j + 1, source.length), '""'); continue;
    }
    if (source[i] === '"' || source[i] === '\'') {
      const quote = source[i];
      let j = i + 1;
      while (j < source.length && source[j] !== quote && source[j] !== '\n') j += source[j] === '\\' ? 2 : 1;
      skip(Math.min(j + 1, source.length), quote + quote); continue;
    }
    out += source[i++];
  }
  return out;
}

const CSHARP = [
  ['#pragma warning disable', /#\s*pragma\s+warning\s+disable/g],
  ['[SuppressMessage]', /\b(?:Unconditional)?SuppressMessage(?:Attribute)?\b/g],
  ['#nullable disable', /#\s*nullable\s+disable/g],
  ['null-forgiving operator (null! / default!)', /\b(?:null|default)\s*!/g],
  ['null-forgiving operator (x!.Member, f(x!))', /(?<=[\w)\]])(?<!\b(?:null|default))!(?=\s*(?:[.[;,)\]?:}]|$))/gm],
];
const CSHARP_RAW = [
  ['<auto-generated> marker (switches the analyzers off for the file)', /<auto-generated/gi],
];
const PROJECT = [
  ['<Nullable> other than enable', /<Nullable>\s*(?!enable\s*<)/gi],
  ['<NoWarn> / NoWarn=', /<NoWarn\b|\bNoWarn\s*=/gi],
  ['<WarningsNotAsErrors>', /<WarningsNotAsErrors\b/gi],
  ['<WarningLevel>', /<WarningLevel\b/gi],
  ['warnings-as-errors switched off', /<(?:MSBuild|CodeAnalysis)?TreatWarningsAsErrors>\s*false/gi],
  ['analyzers switched off', /<(?:RunAnalyzers|RunAnalyzersDuringBuild|EnableNETAnalyzers|EnforceCodeStyleInBuild|GenerateDocumentationFile)>\s*false/gi],
  ['analysis level or mode overridden', /<Analysis(?:Level|Mode)\w*>/gi],
  ['NuGet audit switched off or narrowed', /<NuGetAudit>\s*false|<NuGetAudit(?:Mode|Level)>|<NuGetAuditSuppress\b/gi],
];
const ANY = [
  ['secretlint-disable comment', /secretlint-disable/g],
];

function rulesFor(rel) {
  const path = rel.toLowerCase();
  if (path.endsWith('.cs') || path.endsWith('.csx')) return { code: CSHARP, raw: [...CSHARP_RAW, ...ANY] };
  if (/\.(?:csproj|props|targets)$/.test(path)) return { code: [], raw: [...PROJECT, ...ANY] };
  return { code: [], raw: ANY };
}

/* Every suppression in a file's text: [{ what, line }]. */
export function suppressions(rel, text) {
  const { code, raw } = rulesFor(rel);
  const found = [];
  const scan = (source, rules) => {
    for (const [what, pattern] of rules) {
      for (const m of source.matchAll(pattern)) found.push({ what, line: source.slice(0, m.index).split('\n').length });
    }
  };
  if (code.length) scan(codeOnly(text), code);
  scan(text, raw);
  return found;
}

/* The suppressions an edit adds: those that occur more often in the new text than in the old one. */
export function addedSuppressions(rel, before, after) {
  const count = (text) => suppressions(rel, text).reduce((m, s) => m.set(s.what, (m.get(s.what) ?? 0) + 1), new Map());
  const old = count(before);
  return [...count(after)].filter(([what, n]) => n > (old.get(what) ?? 0)).map(([what]) => what);
}
